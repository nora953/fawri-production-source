export function cashierLocale(lang: Lang): string {
  if (lang === 'en') return 'en-US';
  if (lang === 'ku') return 'ckb-IQ';
  return 'ar-IQ';
}

export function readStoredCashierLanguage(): Lang {
  if (typeof localStorage === 'undefined') return 'ar';
  const value = localStorage.getItem('fawri_lang');
  return value === 'en' || value === 'ku' || value === 'ar' ? value : 'ar';
}

export function storedCashierCopy() {
  return CASHIER_UI_COPY[readStoredCashierLanguage()];
}

